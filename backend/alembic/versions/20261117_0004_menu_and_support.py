    from app.seeds.menu_taxonomy import CATEGORIES, MEAL_TYPES

    conn = op.get_bind()
    tenant_ids = [r[0] for r in conn.execute(sa.text("SELECT id FROM tenants"))]
    for tid in tenant_ids:
        meal_ids = {}
        for i, name in enumerate(MEAL_TYPES):
            meal_ids[name] = conn.execute(
                sa.text(
                    "INSERT INTO menu_meal_types (tenant_id, name, sort_order) VALUES (:t, :n, :o) "
                    "ON CONFLICT (tenant_id, name) DO UPDATE SET name = EXCLUDED.name RETURNING id"
                ),
                {"t": tid, "n": name, "o": i},
            ).scalar_one()
        for i, (cat, meals, subs, alcoholic) in enumerate(CATEGORIES):
            cid = conn.execute(
                sa.text(
                    "INSERT INTO menu_categories (tenant_id, name, sort_order, is_alcoholic, is_active) "
                    "VALUES (:t, :n, :o, :a, :active) "
                    "ON CONFLICT (tenant_id, name) DO UPDATE SET name = EXCLUDED.name RETURNING id"
                ),
                {"t": tid, "n": cat, "o": i, "a": alcoholic, "active": not alcoholic},
            ).scalar_one()
            for m in meals:
                conn.execute(
                    sa.text(
                        "INSERT INTO menu_category_meal_types (tenant_id, category_id, meal_type_id) "
                        "VALUES (:t, :c, :m) ON CONFLICT DO NOTHING"
                    ),
                    {"t": tid, "c": cid, "m": meal_ids[m]},
                )
            for j, sub in enumerate(subs):
                conn.execute(
                    sa.text(
                        "INSERT INTO menu_subcategories (tenant_id, category_id, name, sort_order) "
                        "VALUES (:t, :c, :n, :o) ON CONFLICT DO NOTHING"
                    ),
                    {"t": tid, "c": cid, "n": sub, "o": j},
                )


